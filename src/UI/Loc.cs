    public static string T(string key) =>
        Table.TryGetValue(key, out (string Ko, string En) v) ? (Language == "en" ? v.En : v.Ko) : key;

    public static string F(string key, params object[] args) => string.Format(CultureInfo.InvariantCulture, T(key), args);

    public static string Name(string ko, string en) => Language == "en" && en.Length > 0 ? en : ko;

    public static string Behavior(BehaviorKind b) => T("behavior." + BehaviorKinds.ToId(b));

    public static string Activity(ActivityKind a) => T("activity." + a.ToString().ToLowerInvariant());

    public static string Evidence(EvidenceLevel e) => T("evidence." + EvidenceLevelNames.ToId(e));

    public static string Death(string causeId) => T("death." + causeId);

    public static string Result(BehaviorResult r) => r switch
    {
        BehaviorResult.Completed => T("result.completed"),
        BehaviorResult.Interrupted => T("result.interrupted"),
        BehaviorResult.TargetBlocked => T("result.blocked"),
        BehaviorResult.NoFoodFound => T("result.nofood"),
        BehaviorResult.NoWaterReachable => T("result.nowater"),
        BehaviorResult.NoPreyFound => T("result.noprey"),
        BehaviorResult.ChaseFailed => T("result.chasefailed"),
        BehaviorResult.Kill => T("result.kill"),
        _ => T("result.ongoing"),
    };
